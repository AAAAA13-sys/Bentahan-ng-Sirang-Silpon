async function main() {
  if (existsSync('.env.local')) process.loadEnvFile('.env.local');
  await initializeDatabase();
  const db = await getDb();
  const defaultPassword = await hash('SiliconDemo2026', 12);

  console.log('[*] Seeding verified Philippine repair & scrap sellers...');
  for (const s of sellers) {
    await db.insert(user).values({
      id: s.id,
      name: s.name,
      email: s.email,
      role: 'seller',
      location: s.location,
      sellerVerified: true,
      emailVerified: true,
    }).onConflictDoNothing();

    await db.insert(account).values({
      id: `${s.id}-credential`,
      accountId: s.id,
      providerId: 'credential',
      userId: s.id,
      password: defaultPassword,
    }).onConflictDoNothing();
  }

  console.log(`[*] Flooding database with ${listingsData.length} authentic Facebook Marketplace scrap phone listings...`);
  let inserted = 0;
  for (const l of listingsData) {
    const existing = await db.select({ id: listing.id }).from(listing).where(eq(listing.title, l.title)).limit(1);
    if (!existing.length) {
      await db.insert(listing).values({
        sellerId: l.sellerId,
        title: l.title,
        brand: l.brand,
        model: l.model,
        category: l.category,
        condition: l.condition,
        boardClass: l.boardClass,
        storageGb: l.storageGb,
        ramGb: l.ramGb,
        icCode: l.icCode,
        description: l.description,
        diagnostics: l.diagnostics,
        priceCentavos: l.priceCentavos,
        quantity: l.quantity,
        minimumQuantity: l.minimumQuantity,
        art: l.art,
        isActive: true,
        stockVersion: 0,
      });
      inserted++;
    }
  }

  console.log(`[+] Database flood complete: ${inserted} new listings added (${listingsData.length} total curated items).`);
}

main()
  .catch(err => {
    console.error('[!] Flood failed:', err);
    process.exitCode = 1;
  })
  .finally(() => closeDatabase());
